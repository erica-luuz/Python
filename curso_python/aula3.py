"""
Python = Lingauagem de Programação
Tipo de tipagem = Dinâmica / Forte
str -> string -> texto
Strings são textos que estãp dentro de aspas
"""
print(1234) # ele sabe qaue nao é uma string

# Aspas simples
print('Erica Luz')
print(1, 'Erica "Luz"')

# Aspas duplas
print("Erica Luz")
print(2, "Erica 'Luz'")

# Escape
print("Erica \"Luz\"")

# r
print(r"Erica \"Luz\"")
